package ai.shreds.shared.enums;

/**
 * Enumeration representing priority levels
 * for procurement requests and orders.
 */
public enum SharedEnumPriority {
    
    /** 
     * High priority - requires expedited processing 
     */
    HIGH,
    
    /** 
     * Medium priority - standard processing timeframes 
     */
    MEDIUM,
    
    /** 
     * Low priority - can be processed with lower urgency 
     */
    LOW
}